def test_noncanonical_j_motif_not_turned_into_deletion(tmp_path):
    chars = list(RF128)
    for label in ('118', '119'):
        chars[LABELS.index(label)] = 'S'
    variant = ''.join(chars)
    report = audit_file(fasta(tmp_path, 'variant.fasta', variant), FrozenNumberer({variant: (LABELS, 'H')}))
    flagged = {r['imgt_labels'][0] for r in events(report, 'noncanonical_anchor')}
    assert {'118', '119'} <= flagged
    assert report['domains'][0]['sequence'] == variant
    assert not any('deletion' in r['code'] for r in events(report))


def test_invalid_record_does_not_block_other_records_or_enter_model(tmp_path):
    path = tmp_path / 'mixed.fasta'
    bad = RF128[:20] + 'X' + RF128[21:]
    path.write_text(f'>bad\n{bad}\n>good\n{RF128}\n', encoding='ascii')
    n = FrozenNumberer()
    report = audit_file(path, n)
    assert report['domain_count'] == 1 and report['domains'][0]['record_id'] == 'good'
    assert bad not in n.calls
    assert events(report, 'invalid_sequence_symbols')[0]['certainty'] == 'observed'


