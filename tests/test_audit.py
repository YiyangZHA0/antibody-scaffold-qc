@pytest.mark.integration
def test_real_partial_model_tail_does_not_inflate_reference_deletion(tmp_path, real_numberer):
    # ANARCII can leave twelve existing CDR3 residues unnumbered when FR4 is
    # removed. A supplied exact reference must not report those twelve as absent.
    short = RF128[:-11]
    report = audit_file(fasta(tmp_path, 'no_fr4.fasta', short), real_numberer,
                        reference_path=fasta(tmp_path, 'ref.fasta', RF128))
    changes = events(report, 'reference_terminal_deletion')
    assert sum(len(r['evidence']['reference_residues']) for r in changes) == 11
    assert all(r['region'] == 'FR4' for r in changes)


