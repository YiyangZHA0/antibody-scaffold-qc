def raw_positions(sequence, labels):
    return [((int(re.match(r'\d+', label)[0]), re.sub(r'^\d+', '', label) or ' '), aa)
            for label, aa in zip(labels, sequence)]


class FrozenNumberer:
    engine = 'test_fixture'
    version = 'frozen_3EAK_IMGT_20261110'

    def __init__(self, extra=None):
        self.sequences = {RF128: (LABELS, 'H')}
        self.sequences.update(extra or {})
        self.calls = []

    def _number_one(self, sequence):
        self.calls.append(sequence)
        if sequence in self.sequences:
            labels, chain = self.sequences[sequence]
            return [(raw_positions(sequence, labels), chain, 30.0, 0)]
        return []


def fasta(tmp_path, name, sequence, record='H'):
    path = tmp_path / name
    path.write_text(f'>{record}\n{sequence}\n', encoding='ascii')
    return path


def events(report, code=None):
    result = report['risks'] + [r for d in report['domains'] for r in d['risks']]
    return result if code is None else [r for r in result if r['code'] == code]


def test_sequence_only_never_claims_coordinate_completeness(tmp_path):
    report = audit_file(fasta(tmp_path, 'full.fasta', RF128), FrozenNumberer())
    assert report['domain_count'] == 1
    d = report['domains'][0]
    assert d['sequence'] == RF128
    assert all(not fr['coordinate_assessed'] for fr in d['regions'].values())
    assert all(fr['missing_positive_CA_count'] is None for fr in d['regions'].values())
    assert all(fr['sequence_completeness'] == 'not_established_without_construct_reference'
               for fr in d['regions'].values())
    assert events(report, 'coordinates_not_supplied')[0]['certainty'] == 'not_assessable'
    assert not events(report, 'missing_residue_coordinates')


def test_natural_numbering_gaps_are_not_sequence_deletions(tmp_path):
    report = audit_file(fasta(tmp_path, 'full.fasta', RF128), FrozenNumberer())
    labels = {r['imgt_label'] for r in report['domains'][0]['rows']}
    assert '10' not in labels and '73' not in labels and '111A' in labels
    assert not any('deletion' in r['code'] or 'truncation' in r['code'] for r in events(report))
    assert not events(report, 'outside_typical_fr_length')


def test_ten_residue_fr4_not_confirmed_truncated_without_reference(tmp_path):
    short = RF128[:-1]
    n = FrozenNumberer({short: (LABELS[:-1], 'H')})
    report = audit_file(fasta(tmp_path, 'short.fasta', short), n)
    assert report['domains'][0]['regions']['FR4']['length'] == 10
    assert not events(report, 'possible_c_terminal_truncation')
    assert not events(report, 'reference_terminal_deletion')


def test_exact_construct_reference_exposes_last_s_difference(tmp_path):
    short = RF128[:-1]
    n = FrozenNumberer({short: (LABELS[:-1], 'H')})
    report = audit_file(fasta(tmp_path, 'short.fasta', short), n,
                        reference_path=fasta(tmp_path, 'ref.fasta', RF128))
    changes = events(report, 'reference_terminal_deletion')
    assert len(changes) == 1
    assert changes[0]['certainty'] == 'reference_relative'
    assert changes[0]['region'] == 'FR4'
    assert changes[0]['evidence']['reference_residues'] == 'S'
    assert changes[0]['evidence']['side'] == 'C'
    assert report['domains'][0]['sequence'] == short


def test_missing_n_prefix_is_reference_relative_not_repaired(tmp_path):
    short = RF128[5:]
    n = FrozenNumberer({short: (LABELS[5:], 'H')})
    input_path = fasta(tmp_path, 'short.fasta', short)
    original = input_path.read_bytes()
    report = audit_file(input_path, n, reference_path=fasta(tmp_path, 'ref.fasta', RF128))
    changes = events(report, 'reference_terminal_deletion')
    assert changes[0]['region'] == 'FR1'
    assert changes[0]['evidence']['reference_residues'] == RF128[:5]
    assert changes[0]['evidence']['side'] == 'N'
    assert events(report, 'possible_n_terminal_truncation')
    assert input_path.read_bytes() == original


